const CHARS = Object.keys(G);
const INDEX: Record<string, number> = {};
CHARS.forEach((c, i) => (INDEX[c] = i));

export const GLYPH_W = 6; // 5 px + 1 spacing
export const GLYPH_H = 8;

const atlases = new Map<string, Surface>();

const atlasFor = (color: string): Surface => {
  let s = atlases.get(color);
  if (s) return s;
  s = createSurface(CHARS.length * GLYPH_W, GLYPH_H);
  const ctx = s.ctx;
  if (ctx) {
    ctx.fillStyle = color;
    CHARS.forEach((c, i) => {
      const rows = G[c];
      for (let y = 0; y < 7; y++) {
        for (let x = 0; x < 5; x++) {
          if (rows[y] & (1 << (4 - x))) ctx.fillRect(i * GLYPH_W + x, y, 1, 1);
        }
      }
    });
  }
  atlases.set(color, s);
  return s;
};

export const textWidth = (str: string, scale = 1): number => str.length * GLYPH_W * scale - scale;

export type Align = 'left' | 'center' | 'right';

const drawRaw = (
  ctx: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  color: string,
  scale: number
) => {
  const atlas = atlasFor(color).canvas;
  for (let i = 0; i < str.length; i++) {
    let ch = str[i];
    if (INDEX[ch] === undefined) ch = ch.toUpperCase();
    const gi = INDEX[ch];
    if (gi === undefined) continue;
    ctx.drawImage(atlas, gi * GLYPH_W, 0, 5, 7, x + i * GLYPH_W * scale, y, 5 * scale, 7 * scale);
  }
};

/**
 * Draw arcade text. `shadow` draws a dark drop shadow (and at scale >= 2 a full
 * outline) so text reads over any background.
 */
export const drawText = (
  ctx: CanvasRenderingContext2D,
  str: string,
  x: number,
  y: number,
  color = '#ffffff',
  scale = 1,
  align: Align = 'left',
  shadow: string | null = '#170d22'
): void => {
  const w = textWidth(str, scale);
  let sx = x;
  if (align === 'center') sx = x - Math.floor(w / 2);
  else if (align === 'right') sx = x - w;
  sx = Math.round(sx);
  const sy = Math.round(y);
  if (shadow) {
    if (scale >= 2) {
      for (let oy = -1; oy <= 1; oy++)
        for (let ox = -1; ox <= 1; ox++)
          if (ox || oy) drawRaw(ctx, str, sx + ox, sy + oy, shadow, scale);
      drawRaw(ctx, str, sx + 1, sy + 2, shadow, scale);
    } else {
      drawRaw(ctx, str, sx + 1, sy + 1, shadow, scale);
    }
  }
  drawRaw(ctx, str, sx, sy, color, scale);
};
