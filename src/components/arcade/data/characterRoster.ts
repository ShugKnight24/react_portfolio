const LOCAL_STORAGE_KEY = 'arcade_custom_characters';
const LEGACY_STORAGE_KEY = 'v8_custom_characters';

export const getCustomCharacters = (): SpriteCharacter[] => {
  if (typeof window === 'undefined') return [];
  try {
    const raw =
      localStorage.getItem(LOCAL_STORAGE_KEY) ||
      localStorage.getItem(LEGACY_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
};

export const saveCustomCharacter = (char: SpriteCharacter) => {
  if (typeof window === 'undefined') return;
  const current = getCustomCharacters().filter((c) => c.id !== char.id);
  const updated = [char, ...current];
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(updated));
  } catch {
    // ignore
  }
};

export const deleteCustomCharacter = (id: string) => {
  if (typeof window === 'undefined') return;
  const current = getCustomCharacters().filter((c) => c.id !== id);
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(current));
  } catch {
    // ignore
  }
};
